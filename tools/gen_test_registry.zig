//! Host CLI that generates the test registry (src/tests.zig) from the src
//! tree. Invoked from build.zig as a native executable step (NOT part of the
//! agate library).
//!
//! Zig 0.17 split `zig build` into a configurer process (build.zig logic)
//! and a maker process, and the configurer is no longer allowed to resolve
//! paths out of the build graph (`LazyPath.getPath`/`getPath3` are gone) —
//! the configure-time directory walk this tool replaces lived exactly on
//! that forbidden path and silently kept a stale registry under the new
//! config cache (adding a test file would not rerun the walk). The walk now
//! runs in the make phase: every `zig build test` / `zig build update-tests`
//! re-executes this tool over the CURRENT tree.
//!
//! Why a walk at all: registry completeness is the point. `refAllDecls`?
//! One level only: files whose decls nothing references stay unanalyzed,
//! and their tests silently vanish — exactly the rot we are guarding
//! against. A directory walk is total: every module file is imported, dead
//! or uncompiled files surface as build errors.
//!
//! Zig 0.16 requires `@import` operands to be string literals, so the
//! generated literals must live in a real file. That file is tracked as
//! src/tests.zig, but a normal `zig build` (including builds that use agate
//! as a dependency) MUST NOT rewrite it: silent source mutation breaks
//! packaging reproducibility and races with concurrent edits. This tool
//! therefore only WRITES ITS OUTPUT ARGUMENT; build.zig feeds that output
//! either to the staleness check (`zig build test`) or to
//! UpdateSourceFiles (`zig build update-tests`, the explicit
//! make-phase source mutation).
//!
//! Usage:
//!   gen_test_registry --src <src dir> --out <expected_tests.zig>
//!
//! Exclusions mirror the old build.zig walk (see exclude()).

const std = @import("std");

fn fail(comptime fmt: []const u8, args: anytype) noreturn {
    std.debug.print("test registry generation error: " ++ fmt ++ "\n", args);
    std.process.exit(2);
}

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const cwd = std.Io.Dir.cwd();
    const allocator = init.arena.allocator();

    var src_path: []const u8 = "";
    var out_path: []const u8 = "";
    var it = try std.process.Args.Iterator.initAllocator(init.minimal.args, allocator);
    defer it.deinit();
    _ = it.next(); // argv0
    while (it.next()) |arg| {
        const value = it.next() orelse fail("missing value for '{s}'", .{arg});
        if (std.mem.eql(u8, arg, "--src")) src_path = value;
        if (std.mem.eql(u8, arg, "--out")) out_path = value;
    }
    if (src_path.len == 0) fail("--src is required", .{});
    if (out_path.len == 0) fail("--out is required", .{});

    var paths: std.ArrayListUnmanaged([]const u8) = .empty;
    var dir = cwd.openDir(io, src_path, .{ .iterate = true }) catch
        fail("cannot open src dir '{s}'", .{src_path});
    defer dir.close(io);

    var walker = dir.walk(allocator) catch fail("OOM walking src", .{});
    defer walker.deinit();
    while (walker.next(io) catch |err| fail("walk failed: {s}", .{@errorName(err)})) |entry| {
        if (entry.kind != .file) continue;
        if (!std.mem.endsWith(u8, entry.path, ".zig")) continue;
        if (exclude(entry.path)) continue;
        const dup = allocator.dupe(u8, entry.path) catch fail("OOM", .{});
        paths.append(allocator, dup) catch fail("OOM", .{});
    }
    std.mem.sort([]const u8, paths.items, {}, struct {
        fn less(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.order(u8, a, b) == .lt;
        }
    }.less);

    var out: std.Io.Writer.Allocating = .init(allocator);
    out.writer.writeAll(
        \\//! GENERATED by tools/gen_test_registry.zig from the src tree
        \\//! (wired up by build.zig). Do not edit by hand: regenerate with
        \\//! `zig build update-tests`. Every module file under src is
        \\//! imported so its `test` blocks reach the runner; math is a
        \\//! separate build module and is imported by name (its own test
        \\//! block aggregates math/*.zig).
        \\
        \\test {
        \\    _ = @import("math");
        \\
    ) catch fail("OOM", .{});
    for (paths.items) |p| {
        out.writer.print("    _ = @import(\"{s}\");\n", .{p}) catch fail("OOM", .{});
    }
    out.writer.writeAll("}\n") catch fail("OOM", .{});

    var file = cwd.createFile(io, out_path, .{}) catch |e|
        fail("cannot create '{s}': {s}", .{ out_path, @errorName(e) });
    defer file.close(io);
    file.writeStreamingAll(io, out.written()) catch |e|
        fail("cannot write '{s}': {s}", .{ out_path, @errorName(e) });
}

/// Registry exclusions, each with the reason it is imported elsewhere (or not
/// at all) instead of by the generated list.
fn exclude(path: []const u8) bool {
    // Library facade: the test binary's import chain lives here already;
    // importing it from the registry would force-analyze the entire pub
    // facade (refAllDecls-style) and cycle back into the registry.
    if (std.mem.eql(u8, path, "root.zig")) return true;
    // The registry itself.
    if (std.mem.eql(u8, path, "tests.zig")) return true;
    // Separate build module, emitted as the literal `@import("math")`.
    if (std.mem.eql(u8, path, "math.zig")) return true;
    // Aggregated by math.zig's own test block under the "math" module.
    if (std.mem.startsWith(u8, path, "math/")) return true;
    // Host CLI for the build-time shader merge; compiled by build.zig as
    // merge_shader_material on every build, not part of the library.
    if (std.mem.eql(u8, path, "shader_material/tool_main.zig")) return true;
    return false;
}
